"""Every route of the Python template app, from the FastAPI app itself: `docs/python-contract/routes.txt`.

Run with the Python repo's own virtualenv, which has the app installed. Nothing is written to that repo:

    PYTHONDONTWRITEBYTECODE=1 ~/gramkit/.venv/bin/python scripts/python-routes.py > docs/python-contract/routes.txt

Reads the routes as FastAPI matches them, nested includes and prefixes applied, so a route hidden from the schema
(`include_in_schema=False`) is listed too. Mounts are sub-apps, not routes: they go in the header.
"""

import contextlib
import os
import sys

# The app builds its Telegram authenticator at import: any well-formed token does.
os.environ.setdefault("BOT__TOKEN", "123456789:ABCdefGHIjklMNOpqrsTUVwxyz-not-a-real-token")

from fastapi.routing import APIRoute, _IncludedRouter  # noqa: E402
from starlette.routing import Mount, Route  # noqa: E402

# The app logs to stdout at import
with contextlib.redirect_stdout(sys.stderr):
    from app.webhook.app import app

routes: set[tuple[str, str]] = set()
mounts: list[str] = []

for entry in app.routes:
    if isinstance(entry, Mount):
        mounts.append(entry.path)
    elif isinstance(entry, _IncludedRouter):
        for context in entry.effective_route_contexts():
            routes.update((method, context.path_format) for method in context.methods or ())
    elif isinstance(entry, (APIRoute, Route)):
        routes.update((method, entry.path_format) for method in entry.methods or ())
    else:
        sys.exit(f"unknown route type: {type(entry).__name__}")

print("# Generated by scripts/python-routes.py from the Python app. Do not edit.")
print(f"# Mounts, not routes: {' '.join(sorted(mounts))}")
for method, path in sorted(routes, key=lambda route: (route[1], route[0])):
    print(f"{method} {path}")
